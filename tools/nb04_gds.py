("md", r"""
## 2. Read it back with KLayout and audit the geometry

The point of this section is that the numbers in the metadata are **checked
against the file**, not asserted. If the generator and the file disagree, the
file is wrong.

Checks performed:

1. the die is 5 mm x 5 mm;
2. the bus waveguide is the stated width;
3. the nanomagnet elements are 100 nm x 20 nm at a 200 nm pitch;
4. the nanomagnet count matches the metadata;
5. the CPW centre conductor is 2.1 µm wide;
6. every layer declared in the metadata is present in the file.

KLayout returns coordinates in database units, so they are multiplied by
`dbu` to get micrometres.
"""),

("code", r"""
gds_path = REPO / "gds" / "idaten_concept_mask" / "idaten_concept_mask.gds"
ly = db.Layout()
ly.read(str(gds_path))
dbu = ly.dbu
top = ly.top_cell()
print(f"file      : {gds_path.name}  ({gds_path.stat().st_size/1e6:.2f} MB)")
print(f"top cell  : {top.name}")
print(f"dbu       : {dbu} um  (= {dbu*1000:.3f} nm)")

shapes = {}
for li in ly.layer_indices():
    info = ly.get_info(li)
    polys = []
    for it in top.begin_shapes_rec(li):
        sh = it.shape()
        if sh.is_polygon() or sh.is_box() or sh.is_path():
            pts = sh.polygon.each_point_hull()
            polys.append([(p.x * dbu, p.y * dbu) for p in pts])
    shapes[(info.layer, info.datatype)] = polys

print(f"\n{'layer':>6} {'dt':>3}  {'shapes':>7}  bbox size (um)")
for (lnum, dt), polys in sorted(shapes.items()):
    if not polys:
        continue
    xs = [p[0] for poly in polys for p in poly]
    ys = [p[1] for poly in polys for p in poly]
    print(f"{lnum:>6} {dt:>3}  {len(polys):>7}  "
          f"{max(xs)-min(xs):>9.3f} x {max(ys)-min(ys):>9.3f}")
"""),

("code", r"""
def layer_polys(lnum):
    for (l, dt), polys in shapes.items():
        if l == lnum:
            return polys
    return []

checks = []
die = layer_polys(40)
checks.append(("die is 5 mm x 5 mm",
               abs((max(p[0] for p in die[0]) - min(p[0] for p in die[0])) - 5000.0) < 1e-6))

bus = layer_polys(10)
bus_h = max(p[1] for p in bus[0]) - min(p[1] for p in bus[0])
checks.append((f"bus width = {meta['bus_width_um']} um",
               abs(bus_h - meta["bus_width_um"]) < 1e-6))

mtj = layer_polys(14)
mtj_h = max(p[1] for p in mtj[0]) - min(p[1] for p in mtj[0])
mtj_l = max(p[0] for p in mtj[0]) - min(p[0] for p in mtj[0])
checks.append((f"nanomagnet = {meta['cell_nm'][0]} x {meta['cell_nm'][1]} nm",
               abs(mtj_h*1000 - meta["cell_nm"][1]) < 1e-3 and
               abs(mtj_l*1000 - meta["cell_nm"][0]) < 1e-3))
checks.append((f"nanomagnet count = {meta['array_elements']}", len(mtj) == meta["array_elements"]))

# pitch: sort ALL element x positions, then check the spacing is uniform
xs_all = np.array(sorted(min(p[0] for p in poly) for poly in mtj))
pitches = np.unique(np.round(np.diff(xs_all), 6))
checks.append((f"pitch = {meta['array_pitch_um']} um (uniform)",
               len(pitches) == 1 and abs(pitches[0] - meta["array_pitch_um"]) < 1e-6))

cpw = layer_polys(20)
cpw_h = min(max(p[1] for p in poly) - min(p[1] for p in poly) for poly in cpw)
checks.append((f"CPW centre conductor = {meta['cpw_centre_um']} um",
               abs(cpw_h - meta["cpw_centre_um"]) < 1e-6))

declared = set(int(k) for k in meta["layers"])
present = set(l for (l, dt) in shapes)
checks.append(("every declared layer is present", declared.issubset(present)))

print(f"{'check':<46} result")
for name, ok in checks:
    print(f"{name:<46} {'PASS' if ok else 'FAIL'}")
assert all(ok for _, ok in checks), "geometry audit failed"
print("\nall geometry checks passed")
"""),

